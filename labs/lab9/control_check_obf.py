"""ЛР9 — обфускований варіант control_check.py (та сама логіка, ускладнений аналіз).

Застосовані методи протидії (усі — статичні/потоку даних, без виконання прихованого коду й без
протидії налагоджувачу, щоб програма лишалася передбачуваною й безпечною):
  1. Перейменування ідентифікаторів (_a, _b, _s, _w…) — назви нічого не підказують.
  2. Приховування рядка-секрету: контрольний рядок ніде не присутній цілим літералом. Його частини
     розкидані в словнику з переплутаними числовими ключами разом із фальшивими частинами; роздільники
     й двокрапку зібрано з кодів символів (chr), а не записано текстом.
  3. Сплощення потоку керування: блоки, що формують частини, виконуються не в порядку розташування у
     файлі, а за таблицею переходів _ORDER; справжній порядок відновлюється лише під час виконання.
  4. Непрозора умова (_op): завжди істинна, але для читача обидві гілки виглядають досяжними — одна
     гілка робить лише сміттєві обчислення.
  5. Сміттєвий код: обчислення й стани, що не впливають на результат.
  6. Непряме порівняння: замість `==` на літералі — SHA-256 зібраного секрету проти SHA-256 введення
     через hmac.compare_digest (стала за часом звірка; прямого порівняння з літералом у коді немає).

Контрольне значення (те саме, що в control_check.py): 2026_КБЗІ-24-1_Перепеляк_Данило_варіант:14_
"""

from __future__ import annotations

import hashlib
import hmac


def _op(_n: int) -> bool:
    # Непрозора умова: (n*n + n) завжди парне → результат завжди True.
    return ((_n * _n + _n) & 1) == 0


def _h(_x: str) -> bytes:
    return hashlib.sha256(_x.encode("utf-8")).digest()


def _assemble() -> str:
    _sep = chr(0x5F)                       # '_'
    _colon = chr(0x3A)                     # ':'
    # Частини (справжні + фальшиві) під переплутаними ключами:
    _p = {
        7: "Перепеляк",
        2: "2026",
        9: "Данило",
        4: "КБЗІ-24-1",
        5: "варіант" + _colon,
        1: "14",
        3: "DENIED",                       # фальшива частина — у збірку не входить
        8: "admin",                        # фальшива частина
    }
    # Справжній порядок складання (сплощення: не збігається з порядком у словнику):
    _order = (2, 0, 4, 0, 7, 0, 9, 0, 5, 1, 0)
    _acc = []
    _s = 0
    for _k in _order:
        _w = (_s * 3 + 1) & 0xFF           # сміттєвий лічильник стану
        if _k == 0:
            _acc.append(_sep)
        elif _op(_w):                      # завжди істинна — справжня гілка
            _acc.append(_p[_k])
        else:                              # недосяжна гілка: сміття
            _acc.append(_p.get(_k, "")[::-1])
        _s = _w
    return "".join(_acc)


def main() -> None:
    _v = input("Введіть контрольне значення: ")
    if hmac.compare_digest(_h(_assemble()), _h(_v)):
        print("Доступ дозволено")
    else:
        print("Доступ заборонено")


if __name__ == "__main__":
    main()
