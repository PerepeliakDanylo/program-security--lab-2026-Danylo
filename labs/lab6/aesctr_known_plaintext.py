"""ЛР6, кроки 2-6: атака за відомим відкритим текстом на AES-CTR.

Показує, що AES у режимі CTR — це фактично потоковий шифр: шифротекст = відкритий
текст XOR ключова гама. Якщо гаму (key+IV) використати повторно й відомі пара
(відкритий текст ↔ шифротекст), то, не знаючи ключа, можна:
  1) відновити гаму:        Гама = Шифротекст №1 XOR Відкритий текст №1
  2) підробити шифротекст:  Шифротекст №2 = Гама XOR Альтернативний відкритий текст
а «жертва» штатно розшифрує підробку своїм ключем і отримає підставлений текст.

Висновок: CTR дає конфіденційність, але НЕ цілісність/автентичність і НЕ прощає
повторне використання (key, IV). Для захисту від підміни потрібне автентифіковане
шифрування (AES-GCM) — його застосовує сам інструмент (crypto.py, ЛР6 проєктна частина).

Рядок — за шаблоном методички (варіант дволітерний): і оригінал (14), і альтернатива (99)
мають однакову довжину в байтах, тому підробка працює повністю.

Залежність: pip install cryptography
Запуск:     python aesctr_known_plaintext.py
Звірка:     ті самі key/iv можна вставити в CyberChef (AES Encrypt, CTR) і порівняти.
"""

from __future__ import annotations

import os

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

YEAR = "2026"
GROUP = "КБЗІ-24-1"
SURNAME = "Перепеляк"
NAME = "Данило"


def plaintext(variant: str) -> bytes:
    return f"{YEAR}_{GROUP}_{SURNAME}_{NAME}_варіант:{variant}".encode("utf-8")


def aes_ctr(key: bytes, iv: bytes, data: bytes) -> bytes:
    """AES-CTR. У CTR розшифрування = шифрування (той самий XOR з гамою)."""
    enc = Cipher(algorithms.AES(key), modes.CTR(iv)).encryptor()
    return enc.update(data) + enc.finalize()


def xor(a: bytes, b: bytes) -> bytes:
    return bytes(x ^ y for x, y in zip(a, b))


def h(label: str, raw: bytes) -> None:
    print(f"{label:<22} {raw.hex()}")


def main() -> int:
    p1 = plaintext("14")
    p2 = plaintext("99")                 # той самий шаблон, варіант 99
    assert len(p1) == len(p2), "довжини мають збігатися для повної підробки"

    key = os.urandom(32)                 # AES-256
    iv = os.urandom(16)                  # початковий лічильник CTR
    print("Крок 4 — легітимне шифрування (знають ключ):")
    h("Відкритий текст №1", p1)
    h("Ключ №1", key)
    h("Вектор №1 (IV/лічильник)", iv)
    c1 = aes_ctr(key, iv, p1)            # Шифротекст №1
    h("Шифротекст №1", c1)

    print("\nКрок 5 — атака (ключ НЕвідомий, відомі лише P1, C1, алгоритм):")
    gamma = xor(c1, p1)                  # Гама №1 = ключова послідовність
    h("Гама №1 = C1 XOR P1", gamma)
    h("Альт. текст (варіант 99)", p2)
    c2 = xor(gamma, p2)                  # Шифротекст №2 — підроблено БЕЗ ключа
    h("Шифротекст №2 (підробка)", c2)

    print("\nКрок 6 — перевірка: «жертва» штатно розшифровує C2 своїм ключем:")
    recovered = aes_ctr(key, iv, c2)
    h("Розшифровано з C2", recovered)
    print(f"Текст: {recovered.decode('utf-8')}")
    assert recovered == p2, "підробка мала дати саме альтернативний текст"

    print("\nВисновок: не знаючи ключа, за однією парою (P1,C1) відновлено гаму й підроблено")
    print("валідний шифротекст довільного тексту тієї самої довжини; жертва розшифрувала саме")
    print("підставлений текст. CTR забезпечує конфіденційність, але не виявляє підміни й не")
    print("прощає повторне використання (key, IV). Для цілісності — автентифіковане шифрування (AES-GCM).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
